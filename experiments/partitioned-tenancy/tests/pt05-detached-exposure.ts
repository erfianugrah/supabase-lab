/**
 * PT05 - Which step closes the Data API exposure of a detached partition?
 *
 * PT04e and PT02g measured that a partition detached from a tenant-RLS parent
 * (by hand, or by pg_partman retention with retention_keep_table) stays in
 * `public` with RLS off and the legacy anon grant, and anon reads every
 * tenant's rows from it through the Data API. This module applies one
 * candidate step per partition and reads the result the same way.
 *
 * SIDE: managed Pro-org Micro project (lib/project.ts). KEYS: SQL as postgres
 * through the Management query endpoint and the session pooler (port 5432);
 * Data API reads with the legacy anon JWT (anon) and with a tenant-2 user's
 * access token (apikey = anon, app_metadata.tenant_id = 2). Exposed schemas
 * are the project default (`public`, `graphql_public`); `archive` is a new
 * schema that is NOT added to them.
 *
 * Table public.ar_events range by month, RLS on the parent with the tenant
 * policy in the wrapped form. Partitions 2026_04..2026_07 at 1000 rows each
 * (tenants 1 and 2, 500 each), plus the current month.
 *
 *   PT05a  control: plain DETACH of 2026_04, nothing else.
 *   PT05b  REVOKE ALL on 2026_05 from anon, authenticated, BEFORE the detach.
 *   PT05c  DETACH 2026_06, then ALTER TABLE ... SET SCHEMA archive.
 *   PT05d  ALTER TABLE 2026_07 ENABLE ROW LEVEL SECURITY before the detach
 *          (the parent's policy is not copied to the partition).
 *          Each row: schema, relrowsecurity, policy count, anon and
 *          authenticated SELECT privilege, anon USAGE on the schema; anon and
 *          tenant-2 Data API reads at the default profile and, for tables
 *          outside public, with Accept-Profile: archive.
 *   PT05e  pg_partman retention with retention_schema = 'archive': where the
 *          retired children land, what they carry, whether the Data API
 *          reaches them, and whether any retired child is left in public.
 *   PT05f  security advisors after all of the above: which of the PT05
 *          tables are flagged, by which lint.
 *
 * All rows `info` (the module records which step closes the read; none is a
 * pass condition), except setup, which fails the module if it errors.
 *
 * DESTRUCTIVE: creates schemas archive and partman, extension pg_partman and
 * tables on the shared PT project; PT99 deletes the project.
 *
 * Not settled here: a revoke AFTER the detach (reasoned equivalent to PT05b,
 * not run); exposing `archive` later; grants on tables pg_partman creates in
 * other schemas; anything about the parent's own reads (PT01 covers them).
 */
import type { Ctx, TestModule, TestResult } from "../../../harness/src/types.js";
import { mgmt } from "../../../harness/src/mgmt.js";
import {
  awaitExposed,
  brief,
  codeOf,
  currentProject,
  ensureProject,
  pgSession,
  rest,
  rowCount,
  skipWithoutPro,
  sql,
  sqlOk,
  tenantsSeen,
  tenantUser,
  type PtProject,
} from "../lib/project.js";

const SETUP = `
create schema if not exists archive;
create table public.ar_events (
  id bigint generated by default as identity,
  tenant_id int not null,
  created_at timestamptz not null,
  payload text,
  primary key (created_at, id)
) partition by range (created_at);
alter table public.ar_events enable row level security;
create policy tenant_read on public.ar_events for select to authenticated
  using (tenant_id = (select (auth.jwt() -> 'app_metadata' ->> 'tenant_id')::int));
create table public.ar_events_2026_04 partition of public.ar_events for values from ('2026-04-01') to ('2026-05-01');
create table public.ar_events_2026_05 partition of public.ar_events for values from ('2026-05-01') to ('2026-06-01');
create table public.ar_events_2026_06 partition of public.ar_events for values from ('2026-06-01') to ('2026-07-01');
create table public.ar_events_2026_07 partition of public.ar_events for values from ('2026-07-01') to ('2026-08-01');
create table public.ar_events_2026_10 partition of public.ar_events for values from ('2026-10-01') to ('2026-11-01');
insert into public.ar_events (tenant_id, created_at, payload)
select 1 + (g % 2), make_timestamptz(2026, m, 1 + (g % 28), 12, 0, 0, 'UTC'), 'row ' || g
from generate_series(4, 7) m, generate_series(1, 1000) g;`;

const META = (schema: string, table: string) => `
select n.nspname as schema, c.relrowsecurity as rls,
  (select count(*) from pg_policy pol where pol.polrelid = c.oid)::int as policies,
  has_table_privilege('anon', c.oid, 'select') as anon_select,
  has_table_privilege('authenticated', c.oid, 'select') as auth_select,
  has_schema_privilege('anon', n.oid, 'usage') as anon_schema_usage,
  (select count(*) from pg_inherits i where i.inhrelid = c.oid)::int as still_attached,
  c.reltuples::bigint as est_rows
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = '${schema}' and c.relname = '${table}'`;

interface Probe {
  status: number;
  code: string;
  rows: number;
  tenants: string;
}

interface Lint {
  name?: string;
  metadata?: { name?: string; schema?: string };
  detail?: string;
}

const probeOf = (r: Awaited<ReturnType<typeof rest>>): Probe => ({ status: r.status, code: codeOf(r), rows: rowCount(r), tenants: tenantsSeen(r) });
const fmt = (x: Probe) => `${x.status}${x.code ? `/${x.code}` : ""} rows=${x.rows}${x.tenants ? ` [${x.tenants}]` : ""}`;

async function reads(p: PtProject, table: string, tenant2: string, profile?: string) {
  const headers = profile ? { "Accept-Profile": profile } : undefined;
  const path = `/rest/v1/${table}?select=id,tenant_id&limit=2000`;
  const anon = probeOf(await rest(p.host, path, p.keys.anon, { headers }));
  const t2 = probeOf(await rest(p.host, path, p.keys.anon, { bearer: tenant2, headers }));
  return { anon, t2 };
}

const mod: TestModule = {
  id: "PT05",
  title: "Closing the Data API exposure of a detached partition",
  where: "local",
  requires: ["pat", "org"],
  destructive: true,
  async run(ctx: Ctx): Promise<TestResult[]> {
    const skip = skipWithoutPro(ctx, "PT05");
    if (skip) return skip;
    const results: TestResult[] = [];
    let p: PtProject;
    try {
      p = await ensureProject(ctx);
    } catch (e) {
      return [{ id: "PT05", title: "PT05", status: "fail", detail: `provision: ${e instanceof Error ? e.message : String(e)}` }];
    }
    const red = (s: string) => brief(currentProject(), s, 300);
    try {
      await sqlOk(ctx, p.ref, SETUP);
      const t2 = await tenantUser(p, 2);

      // The four hand-applied steps, then one schema-cache reload for all of them.
      const steps: { id: string; table: string; schema: string; title: string; ddl: string[] }[] = [
        { id: "PT05a", table: "ar_events_2026_04", schema: "public", title: "control: plain DETACH, nothing else", ddl: ["alter table public.ar_events detach partition public.ar_events_2026_04"] },
        {
          id: "PT05b",
          table: "ar_events_2026_05",
          schema: "public",
          title: "REVOKE ALL from anon, authenticated before the DETACH",
          ddl: ["revoke all on public.ar_events_2026_05 from anon, authenticated", "alter table public.ar_events detach partition public.ar_events_2026_05"],
        },
        {
          id: "PT05c",
          table: "ar_events_2026_06",
          schema: "archive",
          title: "DETACH, then SET SCHEMA archive (a schema the Data API does not expose)",
          ddl: ["alter table public.ar_events detach partition public.ar_events_2026_06", "alter table public.ar_events_2026_06 set schema archive"],
        },
        {
          id: "PT05d",
          table: "ar_events_2026_07",
          schema: "public",
          title: "ENABLE ROW LEVEL SECURITY on the partition before the DETACH",
          ddl: ["alter table public.ar_events_2026_07 enable row level security", "alter table public.ar_events detach partition public.ar_events_2026_07"],
        },
      ];
      const ddlOut: Record<string, string> = {};
      for (const s of steps) {
        const errs: string[] = [];
        for (const q of s.ddl) {
          const r = await sql(ctx, p.ref, q);
          if (r.status >= 300) errs.push(`${q.split(" ").slice(0, 4).join(" ")}: ${r.error ?? r.status}`);
        }
        ddlOut[s.id] = errs.join("; ") || "ok";
      }
      // The control table becomes visible to PostgREST once the cache reloads; use it as the readiness gate.
      const cacheS = await awaitExposed(ctx, p, `/rest/v1/ar_events_2026_04?select=id&limit=1`, 60_000);

      for (const s of steps) {
        const m = (await sqlOk(ctx, p.ref, META(s.schema, s.table)))[0] ?? {};
        const def = await reads(p, s.table, t2.token);
        const arch = s.schema === "archive" ? await reads(p, s.table, t2.token, "archive") : undefined;
        results.push({
          id: s.id,
          title: `${s.id}: ${s.title}`,
          status: "info",
          detail:
            `ddl ${red(ddlOut[s.id] ?? "")}; ${s.schema}.${s.table}: rls=${m.rls} policies=${m.policies} anon_select=${m.anon_select} authenticated_select=${m.auth_select} anon_schema_usage=${m.anon_schema_usage} attached=${m.still_attached}; ` +
            `default profile anon ${fmt(def.anon)}, tenant 2 ${fmt(def.t2)}` +
            (arch ? `; Accept-Profile archive anon ${fmt(arch.anon)}, tenant 2 ${fmt(arch.t2)}` : "") +
            ` (schema cache ${cacheS}s)`,
          measurements: {
            ddl: red(ddlOut[s.id] ?? "").slice(0, 160),
            schema: String(m.schema ?? ""),
            rls_on: m.rls === true ? 1 : 0,
            policies: Number(m.policies ?? -1),
            anon_select: m.anon_select === true ? 1 : 0,
            authenticated_select: m.auth_select === true ? 1 : 0,
            anon_schema_usage: m.anon_schema_usage === true ? 1 : 0,
            still_attached: Number(m.still_attached ?? -1),
            anon_status: def.anon.status,
            anon_code: def.anon.code,
            anon_rows: def.anon.rows,
            anon_tenants: def.anon.tenants,
            tenant2_status: def.t2.status,
            tenant2_code: def.t2.code,
            tenant2_rows: def.t2.rows,
            tenant2_tenants: def.t2.tenants,
            ...(arch
              ? {
                  archive_profile_anon_status: arch.anon.status,
                  archive_profile_anon_code: arch.anon.code,
                  archive_profile_tenant2_status: arch.t2.status,
                  archive_profile_tenant2_code: arch.t2.code,
                }
              : {}),
            schema_cache_s: cacheS,
          },
        });
      }

      // ---- PT05e: pg_partman retention_schema ----
      const ext = await sql(ctx, p.ref, `create schema if not exists partman; create extension if not exists pg_partman with schema partman;`);
      await sqlOk(
        ctx,
        p.ref,
        `create table public.rp_events (
           id bigint generated by default as identity,
           tenant_id int not null,
           created_at timestamptz not null,
           payload text,
           primary key (created_at, id)
         ) partition by range (created_at);
         alter table public.rp_events enable row level security;
         create policy tenant_read on public.rp_events for select to authenticated
           using (tenant_id = (select (auth.jwt() -> 'app_metadata' ->> 'tenant_id')::int));`,
      );
      const cp = await sql(
        ctx,
        p.ref,
        `select partman.create_parent(
           p_parent_table := 'public.rp_events', p_control := 'created_at', p_type := 'range',
           p_interval := '1 day', p_premake := 2,
           p_start_partition := to_char(now() - interval '10 days', 'YYYY-MM-DD')) as ok`,
      );
      await sqlOk(
        ctx,
        p.ref,
        `insert into public.rp_events (tenant_id, created_at, payload)
         select t, now() - make_interval(days => d) + interval '1 minute', 'd' || d
         from generate_series(0, 9) d, generate_series(1, 2) t`,
      );
      const childrenBefore = Number((await sqlOk(ctx, p.ref, `select count(*)::int as n from pg_inherits where inhparent = 'public.rp_events'::regclass`))[0]?.n ?? -1);
      const cfg = await sql(
        ctx,
        p.ref,
        `update partman.part_config set retention = '5 days', retention_schema = 'archive' where parent_table = 'public.rp_events'`,
      );
      const s = await pgSession(p);
      const maint = await s.query(`call partman.run_maintenance_proc()`);
      await s.close();
      const childrenAfter = Number((await sqlOk(ctx, p.ref, `select count(*)::int as n from pg_inherits where inhparent = 'public.rp_events'::regclass`))[0]?.n ?? -1);
      const moved = await sqlOk(
        ctx,
        p.ref,
        `select c.relname, n.nspname as schema, c.relrowsecurity as rls,
           (select count(*) from pg_policy pol where pol.polrelid = c.oid)::int as policies,
           has_table_privilege('anon', c.oid, 'select') as anon_select,
           (select count(*) from pg_inherits i where i.inhrelid = c.oid)::int as attached
         from pg_class c join pg_namespace n on n.oid = c.relnamespace
         where c.relkind = 'r' and c.relname like 'rp_events_p%' and n.nspname in ('archive', 'public')
           and not exists (select 1 from pg_inherits i where i.inhrelid = c.oid)
         order by 2, 1`,
      );
      const inArchive = moved.filter((r) => r.schema === "archive");
      const inPublic = moved.filter((r) => r.schema === "public");
      let archRead = { def: { status: 0, code: "", rows: -1, tenants: "" } as Probe, prof: { status: 0, code: "", rows: -1, tenants: "" } as Probe, table: "", rowsHeld: -1 };
      if (inArchive.length) {
        const t = String(inArchive[inArchive.length - 1]?.relname);
        await sql(ctx, p.ref, "notify pgrst, 'reload schema'");
        await new Promise((r) => setTimeout(r, 5_000));
        const d = await reads(p, t, t2.token);
        const pr = await reads(p, t, t2.token, "archive");
        const held = Number((await sqlOk(ctx, p.ref, `select count(*)::int as n from archive.${t}`))[0]?.n ?? -1);
        archRead = { def: d.anon, prof: pr.anon, table: t.replace(/\d{8}$/, "<date>"), rowsHeld: held };
      }
      results.push({
        id: "PT05e",
        title: "PT05e: pg_partman retention with retention_schema = 'archive'",
        status: "info",
        detail:
          `pg_partman create ${ext.status} ${red(ext.error ?? "")}; create_parent ${cp.status} ${red(cp.error ?? "")}; retention config ${cfg.status} ${red(cfg.error ?? "")}; maintenance ${maint.error ? red(maint.error) : "ok"}; ` +
          `children ${childrenBefore} -> ${childrenAfter}; retired children in archive ${inArchive.length} (rls on ${inArchive.filter((r) => r.rls === true).length}, policies ${inArchive.filter((r) => Number(r.policies) > 0).length}, anon select ${inArchive.filter((r) => r.anon_select === true).length}), left in public ${inPublic.length}; ` +
          `newest retired (${archRead.table}, ${archRead.rowsHeld} rows): anon default profile ${fmt(archRead.def)}, Accept-Profile archive ${fmt(archRead.prof)}`,
        measurements: {
          create_parent_status: cp.status,
          retention_config_status: cfg.status,
          maintenance_ok: maint.error ? 0 : 1,
          children_before: childrenBefore,
          children_after: childrenAfter,
          retired_in_archive: inArchive.length,
          retired_in_public: inPublic.length,
          retired_rls_on: inArchive.filter((r) => r.rls === true).length,
          retired_with_policies: inArchive.filter((r) => Number(r.policies) > 0).length,
          retired_anon_select: inArchive.filter((r) => r.anon_select === true).length,
          newest_retired_rows: archRead.rowsHeld,
          newest_anon_default_status: archRead.def.status,
          newest_anon_default_code: archRead.def.code,
          newest_anon_archive_profile_status: archRead.prof.status,
          newest_anon_archive_profile_code: archRead.prof.code,
        },
      });

      // ---- PT05f: advisors ----
      const adv = await mgmt(ctx, "GET", `/projects/${p.ref}/advisors/security`);
      const lints = ((adv.json as { lints?: Lint[] } | undefined)?.lints ?? []) as Lint[];
      const tables = [...steps.map((x) => `${x.schema}.${x.table}`), ...inArchive.map((r) => `archive.${String(r.relname)}`)];
      const hits = (l: Lint, st: string) => {
        const [sc, t] = st.split(".");
        return l.metadata?.name !== undefined ? l.metadata.name === t && (l.metadata.schema ?? "public") === sc : new RegExp(`\\b${sc}\\.${t}\\b`).test(l.detail ?? "");
      };
      const byTable = (st: string) => lints.filter((l) => hits(l, st)).map((l) => l.name).sort().join("+") || "none";
      const label = (st: string) => st.replace(/\d{8}$/, "<date>");
      results.push({
        id: "PT05f",
        title: "PT05f: security advisors after PT05a-e",
        status: "info",
        detail: `advisors ${adv.status}; lint names overall: ${[...new Set(lints.map((l) => l.name))].sort().join(",") || "none"}; per table: ${tables.map((t) => `${label(t)}=${byTable(t)}`).join("; ")}`,
        measurements: {
          advisors_status: adv.status,
          ctl_public_detached: byTable(`public.${steps[0]?.table}`),
          revoked_before_detach: byTable(`public.${steps[1]?.table}`),
          moved_to_archive: byTable(`archive.${steps[2]?.table}`),
          rls_on_before_detach: byTable(`public.${steps[3]?.table}`),
          partman_retired_in_archive_flagged: inArchive.filter((r) => byTable(`archive.${String(r.relname)}`) !== "none").length,
        },
      });
    } catch (e) {
      results.push({ id: "PT05", title: "PT05", status: "fail", detail: red(e instanceof Error ? e.message : String(e)) });
    }
    return results;
  },
};
export default mod;
