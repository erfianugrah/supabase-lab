/**
 * SD12's compose layer: run chosen services from their linux/amd64 images on
 * an arm64 engine (emulation, not native amd64).
 *
 * The images are referenced by the amd64 manifest digest, not by tag: on an
 * engine with the classic image store a `--platform linux/amd64` pull of a tag
 * re-points that tag at the amd64 image, and every other stack on the engine
 * that runs the same tag would then start emulated. A digest pull adds an
 * image without touching any tag. Usage (the Makefile's `amd64-layer` target):
 *
 *   bun lib/amd64-layer.ts <stack dir> <service>...
 *
 * writes <stack dir>/docker-compose.amd64.yml for `make up LAYERS=amd64`.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

interface IndexManifest {
  digest: string;
  platform?: { architecture?: string; os?: string; variant?: string };
}

/** The linux/amd64 manifest digest in an OCI image index or Docker manifest list, or null. */
export function amd64Digest(index: { manifests?: IndexManifest[] }): string | null {
  const m = (index.manifests ?? []).find((x) => x.platform?.os === "linux" && x.platform?.architecture === "amd64");
  return m?.digest ?? null;
}

/** `repo:tag` (or `repo`) plus a digest -> `repo@digest`. */
export function byDigest(image: string, digest: string): string {
  const at = image.indexOf("@");
  const base = at >= 0 ? image.slice(0, at) : image;
  const slash = base.lastIndexOf("/");
  const colon = base.lastIndexOf(":");
  return `${colon > slash ? base.slice(0, colon) : base}@${digest}`;
}

async function run(cmd: string[], cwd?: string): Promise<string> {
  const p = Bun.spawn(cmd, { cwd, stdout: "pipe", stderr: "pipe" });
  const [out, err] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text()]);
  if ((await p.exited) !== 0) throw new Error(`${cmd.join(" ")}: ${err.trim().slice(0, 300)}`);
  return out;
}

if (import.meta.main) {
  const [dir, ...services] = process.argv.slice(2);
  if (!dir || services.length === 0) {
    console.error("usage: bun lib/amd64-layer.ts <stack dir> <service>...");
    process.exit(2);
  }
  const model = JSON.parse(await run(["docker", "compose", "-f", "docker-compose.yml", "config", "--format", "json"], dir));
  const lines = ["# Generated by lib/amd64-layer.ts: linux/amd64 images by manifest digest (emulated on arm64).", "services:"];
  for (const s of services) {
    const image = String(model.services?.[s]?.image ?? "");
    if (!image) throw new Error(`no image for service ${s}`);
    const digest = amd64Digest(JSON.parse(await run(["docker", "buildx", "imagetools", "inspect", "--raw", image])));
    if (!digest) throw new Error(`${image}: no linux/amd64 manifest`);
    lines.push(`  ${s}:`, `    image: ${byDigest(image, digest)}`, `    platform: linux/amd64`);
    console.log(`${s}: ${image} -> amd64 ${digest.slice(0, 19)}...`);
  }
  writeFileSync(join(dir, "docker-compose.amd64.yml"), `${lines.join("\n")}\n`);
}
