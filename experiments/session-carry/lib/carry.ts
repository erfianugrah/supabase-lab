/** The JWT header, decoded without verifying - `kid` is what routes verification. */
export function header(token: string): Record<string, unknown> {
  const part = token.split(".")[0];
  if (!part) return {};
  try {
    return JSON.parse(Buffer.from(part, "base64url").toString("utf8")) as Record<string, unknown>;
  } catch {
    return {};
  }
}

export const str = (v: unknown): string | undefined => (typeof v === "string" ? v : undefined);

/** Any auth endpoint, any method. Success bodies are never recorded by callers - they carry live tokens. */
export async function authReq(
  ref: string,
  method: string,
  path: string,
  apikey: string,
  bearer?: string,
  body?: unknown,
): Promise<AuthResponse> {
  const res = await fetch(`https://${host(ref)}/auth/v1${path}`, {
    method,
    headers: {
      apikey,
      ...(bearer ? { Authorization: `Bearer ${bearer}` } : {}),
      ...(body !== undefined ? { "Content-Type": "application/json" } : {}),
    },
    body: body !== undefined ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(30000),
  });
  const text = await res.text();
  let json: Record<string, unknown> = {};
  try {
    json = JSON.parse(text) as Record<string, unknown>;
  } catch {
    /* non-json */
  }
  return { status: res.status, json, text };
}

/** Error body with any token-looking string stripped, for evidence. */
export function errText(r: { status: number; json: Record<string, unknown>; text: string }): string {
  if (r.status < 300) return `HTTP ${r.status}`;
  const code = str(r.json.error_code) ?? str(r.json.code) ?? str(r.json.error) ?? "";
  const msg = str(r.json.msg) ?? str(r.json.message) ?? str(r.json.error_description) ?? "";
  return `HTTP ${r.status} ${code} ${msg}`.trim().slice(0, 200);
}

// ---- The imported signing key ----

/**
 * The key owner holds the private key and imports it into both projects, which
 * is what makes "same kid on both" possible at all - a key generated BY a
 * project cannot be extracted. Generated here per run with WebCrypto, the kid a
 * fresh UUID (the Management API's private_jwk.kid is uuid-patterned).
 */
export async function generateEs256Jwk(): Promise<Record<string, unknown>> {
  const pair = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, [
    "sign",
    "verify",
  ]);
  const jwk = (await crypto.subtle.exportKey("jwk", pair.privateKey)) as Record<string, unknown>;
  return {
    kty: "EC",
    crv: "P-256",
    x: jwk.x,
    y: jwk.y,
    d: jwk.d,
    kid: randomUUID(),
    alg: "ES256",
    use: "sig",
    key_ops: ["sign", "verify"],
    ext: true,
  };
}

export async function importSigningKey(
  ctx: Ctx,
  ref: string,
  privateJwk: Record<string, unknown>,
): Promise<{ status: number; json?: unknown; text: string }> {
  return mgmt(ctx, "POST", `/projects/${ref}/config/auth/signing-keys`, {
    algorithm: "ES256",
    status: "standby",
    private_jwk: privateJwk,
  });
}

/**
 * A project holds at most 3 previously_used keys; the next import answers 422
 * "There already are 3 previously used signing keys" (measured 2026-09-25 on
 * the second S01 run). Revoke the oldest asymmetric one to make room. Never
 * the HS256 legacy secret: the legacy anon/service JWTs the harness uses are
 * signed with it.
 */
export async function makeRoom(ctx: Ctx, ref: string): Promise<string | undefined> {
  const ks = (await listSigningKeys(ctx, ref)) as (SigningKey & { algorithm?: string; created_at?: string })[];
  const prev = ks.filter((k) => k.status === "previously_used");
  if (prev.length < 3) return undefined;
  const victim = prev
    .filter((k) => k.algorithm !== "HS256")
    .sort((a, b) => String(a.created_at).localeCompare(String(b.created_at)))[0];
  if (!victim) return undefined;
  await mgmt(ctx, "PATCH", `/projects/${ref}/config/auth/signing-keys/${victim.id}`, { status: "revoked" });
  return victim.kid;
}

/**
 * The kid both projects are signing with, if they agree. S02-S04 read this
 * from the platform rather than from a variable S01 left behind, so each module
 * says for itself whether its precondition holds.
 */
export async function sharedInUseKid(ctx: Ctx, a: string, b: string): Promise<string | undefined> {
  const [ka, kb] = await Promise.all([listSigningKeys(ctx, a), listSigningKeys(ctx, b)]);
  const ina = ka.find((k) => k.status === "in_use")?.kid;
  const inb = kb.find((k) => k.status === "in_use")?.kid;
  return ina && ina === inb ? ina : undefined;
}

export async function jwksKids(ref: string): Promise<string[]> {
  const res = await fetch(`https://${host(ref)}/auth/v1/.well-known/jwks.json`, {
    signal: AbortSignal.timeout(15000),
  });
  try {
    const j = (await res.json()) as { keys?: { kid?: string }[] };
    return (j.keys ?? []).map((k) => String(k.kid ?? ""));
  } catch {
    return [];
  }
}

/** Poll `probe` until it returns true or the budget runs out; the elapsed ms, or -1. */
export async function pollUntil(
  probe: () => Promise<boolean>,
  budgetMs: number,
  stepMs = 5000,
): Promise<number> {
  const t0 = performance.now();
  while (performance.now() - t0 < budgetMs) {
    if (await probe()) return Math.round(performance.now() - t0);
    await new Promise((x) => setTimeout(x, stepMs));
  }
  return -1;
}

// ---- A user with a live session at the source ----

export interface Session {
  email: string;
  uid: string;
  access: string;
  refresh: string;
}

export async function newSession(
  srcRef: string,
  k: { anon: string; service: string },
  tagName: string,
): Promise<Session | { error: string }> {
  const email = `${tagName}-${RUN}@lab.invalid`;
  const c = await adminCreate(host(srcRef), k.service, {
    email,
    password: PASSWORD,
    email_confirm: true,
  });
  if (c.status >= 300) return { error: `adminCreate ${errText(c)}` };
  const l = await login(host(srcRef), k.anon, email);
  const access = str(l.json.access_token);
  const refresh = str(l.json.refresh_token);
  if (!access || !refresh) return { error: `login ${errText(l)}` };
  return { email, uid: String(claims(access).sub ?? ""), access, refresh };
}

// ---- The copy ----

export const CORE_TABLES = ["users", "identities", "sessions", "refresh_tokens", "mfa_factors"];

/**
 * Copy one user's auth rows in FK order, then resync the refresh token
 * sequence. `extra` appends tables after the core five (S04 uses it for
 * mfa_amr_claims, which a five-table copy leaves out). One TestResult per
 * table; `read` is recorded because an empty insert succeeds.
 */
export async function copyUser(
  ctx: Ctx,
  from: string,
  to: string,
  uid: string,
  idPrefix: string,
  extra: string[] = [],
): Promise<{ results: TestResult[]; ok: boolean }> {
  const results: TestResult[] = [];
  let ok = true;
  for (const t of [...CORE_TABLES, ...extra]) {
    const where =
      t === "users"
        ? `id = '${uid}'`
        : t === "refresh_tokens"
          ? `user_id::text = '${uid}'`
          : t === "mfa_amr_claims"
            ? `session_id in (select id from auth.sessions where user_id = '${uid}')`
            : `user_id = '${uid}'`;
    const rewrite: Record<string, string> =
      t === "refresh_tokens" ? { id: "nextval('auth.refresh_tokens_id_seq')" } : {};
    const c = await copyTable(ctx, from, to, "auth", t, where, rewrite);
    // mfa_factors legitimately has zero rows for a user who never enrolled.
    const needRows = t !== "mfa_factors";
    const good = c.result.status < 300 && !c.dump.error && (!needRows || c.read > 0);
    if (!good) ok = false;
    results.push({
      id: `${idPrefix}-${t}`,
      title: `auth.${t} copied`,
      status: good ? "pass" : "fail",
      detail: c.dump.error
        ? `dump failed: ${c.dump.error.slice(0, 140)}`
        : `${c.read} row(s) over ${c.cols} columns`,
      measurements: { read: c.read, sqlstate: sqlstate(c.result) },
      evidence: c.result.error?.slice(0, 200),
    });
  }
  const seq = await resyncSequence(ctx, to, "auth.refresh_tokens_id_seq", "auth", "refresh_tokens");
  if (seq.result.status >= 300) ok = false;
  results.push({
    id: `${idPrefix}-seq`,
    title: "auth.refresh_tokens_id_seq resynced",
    status: seq.result.status < 300 ? "pass" : "fail",
    detail: `last_value=${seq.lastValue}`,
  });
  return { results, ok };
}

// ---- TOTP (RFC 6238, SHA1, 6 digits, 30s step) - same as tenant-promotion P02 ----

const B32 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
function base32Decode(s: string): Uint8Array {
  const input = s.toUpperCase().replace(/=+$/, "").replace(/\s/g, "");
  const out = new Uint8Array(Math.floor((input.length * 5) / 8));
  let bits = 0;
  let buf = 0;
  let idx = 0;
  for (const ch of input) {
    const val = B32.indexOf(ch);
    if (val === -1) continue;
    buf = (buf << 5) | val;
    bits += 5;
    if (bits >= 8) {
      bits -= 8;
      out[idx++] = (buf >>> bits) & 0xff;
    }
  }
  return out;
}

export function totp(secretB32: string, ts = Date.now()): string {
  const counterBuf = new Uint8Array(8);
  new DataView(counterBuf.buffer).setBigUint64(0, BigInt(Math.floor(ts / 1000 / 30)));
  const hmac = createHmac("sha1", base32Decode(secretB32)).update(counterBuf).digest();
  const o = hmac[hmac.length - 1]! & 0x0f;
  const bin =
    ((hmac[o]! & 0x7f) << 24) |
    ((hmac[o + 1]! & 0xff) << 16) |
    ((hmac[o + 2]! & 0xff) << 8) |
    (hmac[o + 3]! & 0xff);
  return String(bin % 1000000).padStart(6, "0");
}

/**
 * Enrol and verify a TOTP factor on the session, returning the aal2 session
 * the verify call mints. The verify response carries a fresh refresh token
 * too - that is the one an MFA'd browser would hold.
 */
export async function stepUpToAal2(
  ref: string,
  anon: string,
  s: Session,
): Promise<{ access: string; refresh: string } | { error: string }> {
  const e = await authReq(ref, "POST", "/factors", anon, s.access, {
    factor_type: "totp",
    friendly_name: `sc-${RUN}`,
  });
  const fid = str(e.json.id);
  const secret = str((e.json.totp as Record<string, unknown> | undefined)?.secret);
  if (!fid || !secret) return { error: `enrol ${errText(e)}` };
  const ch = await authReq(ref, "POST", `/factors/${fid}/challenge`, anon, s.access, {});
  const cid = str(ch.json.id);
  if (!cid) return { error: `challenge ${errText(ch)}` };
  const v = await authReq(ref, "POST", `/factors/${fid}/verify`, anon, s.access, {
    challenge_id: cid,
    code: totp(secret),
  });
  const access = str(v.json.access_token);
  const refresh = str(v.json.refresh_token);
  if (!access || !refresh) return { error: `verify ${errText(v)}` };
  return { access, refresh };
}

