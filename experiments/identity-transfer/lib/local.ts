/**
 * The local-rig vantage: the same sign-in flow against a throwaway GoTrue in
 * Docker (local/compose.yml), and SQL straight to its Postgres.
 *
 * It exists because the questions the ITL modules ask are about the Auth
 * server's own code - which stored copies of the provider claims a sign-in
 * rewrites, where a custom claim lands and how long it survives, which
 * account-resolution decision arms the Before User Created hook - and those
 * files are byte-identical between the pinned image and master. The managed
 * vantage answers a different question (what the platform's config surface
 * exposes), and needs a PAT.
 *
 * Two differences from the managed flow, both structural: self-hosted GoTrue
 * serves its routes at the root rather than under /auth/v1, and takes no
 * apikey. Provider config is environment, so there is no config PATCH and
 * nothing to poll for a settle.
 */
import { Client } from "pg";
import type { Persona, SignIn } from "./flow";
import { b64url, jwtPayload } from "./flow";

/**
 * The rig's Postgres. The password is a container-local throwaway generated by
 * `make local-up`, not a credential: the database is published on loopback
 * only and is destroyed with the rig.
 */
export const localDsn = (): string => {
  const pw = process.env.PVLAB_LOCAL_DB_PASSWORD ?? "";
  const host = process.env.PVLAB_LOCAL_DB_HOST ?? "127.0.0.1";
  const port = process.env.PVLAB_LOCAL_DB_PORT ?? "5433";
  return `postgres://postgres:${pw}@${host}:${port}/postgres`;
};

/** One query, one connection. The modules here run a handful of reads each. */
export async function q(text: string): Promise<Record<string, unknown>[]> {
  const c = new Client({ connectionString: localDsn(), connectionTimeoutMillis: 10_000 });
  await c.connect();
  try {
    const r = await c.query(text);
    return r.rows as Record<string, unknown>[];
  } finally {
    await c.end();
  }
}

/** Is the rig answering? Used to self-skip rather than fail when it is down. */
export async function rigUp(base: string): Promise<boolean> {
  try {
    const r = await fetch(`${base}/health`, { signal: AbortSignal.timeout(5_000) });
    return r.status === 200;
  } catch {
    return false;
  }
}

/**
 * The browser flow followed by hand, against the local rig: GoTrue /authorize
 * -> issuer /auth (persona appended) -> GoTrue /callback -> site_url with
 * tokens or an error in the fragment.
 */
export async function signInLocal(base: string, persona: Persona): Promise<SignIn> {
  const r1 = await fetch(`${base}/authorize?provider=keycloak`, { redirect: "manual", signal: AbortSignal.timeout(30_000) });
  const issuerAuth = r1.headers.get("location");
  if (r1.status !== 302 || !issuerAuth) {
    const body = (await r1.text()).slice(0, 300);
    return { authorizeStatus: r1.status, callbackStatus: -1, error: `authorize did not redirect: ${body}` };
  }
  const u = new URL(issuerAuth);
  u.searchParams.set("persona", b64url(JSON.stringify(persona)));
  const r2 = await fetch(u, { redirect: "manual", signal: AbortSignal.timeout(30_000) });
  const callback = r2.headers.get("location");
  if (r2.status !== 302 || !callback) {
    return { authorizeStatus: r1.status, callbackStatus: -1, error: `issuer did not redirect: HTTP ${r2.status}` };
  }
  const r3 = await fetch(callback, { redirect: "manual", signal: AbortSignal.timeout(30_000) });
  const landing = r3.headers.get("location");
  if (!landing) {
    const body = (await r3.text()).slice(0, 300);
    return { authorizeStatus: r1.status, callbackStatus: r3.status, error: `callback did not redirect: ${body}` };
  }
  const l = new URL(landing);
  const frag = new URLSearchParams(l.hash.replace(/^#/, ""));
  const pick = (k: string) => frag.get(k) ?? l.searchParams.get(k) ?? undefined;
  const out: SignIn = { authorizeStatus: r1.status, callbackStatus: r3.status, landed: `${l.host}${l.pathname}` };
  const access = pick("access_token");
  if (access) {
    const p = jwtPayload(access);
    out.userId = typeof p.sub === "string" ? p.sub : undefined;
    out.email = typeof p.email === "string" ? p.email : undefined;
  } else {
    out.error = pick("error");
    out.errorCode = pick("error_code");
    out.errorDescription = pick("error_description");
  }
  return out;
}

/** Delete everything a run created, keyed on the run's subject prefix. */
export async function sweep(prefix: string): Promise<number> {
  const rows = await q(`delete from auth.users where id in (select user_id from auth.identities where provider = 'keycloak' and provider_id like '${prefix}%') or email like '${prefix}%' returning id`);
  return rows.length;
}
