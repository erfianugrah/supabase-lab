#!/usr/bin/env bun
/**
 * Emits lib/studio-sql.generated.ts: the exact SQL Studio sends for the
 * Wrappers create / edit / delete actions, produced by Studio's own pg-meta
 * functions rather than a hand copy (the hand copy got the BigQuery secret
 * name wrong - sa_key instead of sa_key_id).
 *
 *   git -C <supabase> archive origin/master packages/pg-meta | tar -x -C <dir>
 *   bun scripts/gen-studio-sql.ts <dir>/packages/pg-meta/src <commit>
 *
 * wrapperMeta and formState mirror apps/studio: Wrappers.constants.ts
 * (bigquery_wrapper), CreateWrapperSheet (server_name = `${wrapper_name}_server`),
 * EditWrapperSheet (formState = the row's wrapper_name + server_name + options),
 * and the fdw-*-mutation files, which each wrap the SQL in wrapWithTransaction.
 */
import { resolve } from "node:path";

const [srcArg, commit] = process.argv.slice(2);
if (!srcArg || !commit) {
  console.error("usage: gen-studio-sql.ts <pg-meta/src> <supabase commit>");
  process.exit(1);
}
const src = resolve(srcArg);
const fdw = await import(`${src}/sql/studio/database/fdw.ts`);
const { wrapWithTransaction } = await import(`${src}/query/Query.utils.ts`);

// Wrappers.constants.ts, bigquery_wrapper entry.
const wrapperMeta = {
  handlerName: "big_query_fdw_handler",
  validatorName: "big_query_fdw_validator",
  server: {
    options: [
      { name: "sa_key_id", encrypted: true },
      { name: "project_id", encrypted: false },
      { name: "dataset_id", encrypted: false },
    ],
  },
};

// Dummy credentials: the catalog is exercised, BigQuery is never contacted.
const creds = { sa_key_id: "{}", project_id: "lab-project", dataset_id: "lab_dataset" };

const table = (schema: string, name: string, isNew = false) => ({
  schema_name: schema,
  table_name: name,
  is_new_schema: isNew,
  columns: [
    { name: "id", type: "bigint" },
    { name: "v", type: "text" },
  ],
  table: name,
});

/** CreateWrapperSheet -> fdw-create-mutation. */
const create = (wrapperName: string, schema: string, tbl: string, isNewSchema = false): string =>
  wrapWithTransaction(
    fdw.getCreateFDWSql({
      wrapperMeta,
      formState: { wrapper_name: wrapperName, ...creds, server_name: `${wrapperName}_server` },
      mode: "tables",
      tables: [table(schema, tbl, isNewSchema)],
      sourceSchema: "",
      targetSchema: "",
    }),
  );

/** DeleteWrapperModal -> fdw-delete-mutation. `name` is the list row's name, i.e. the FDW name. */
const del = (name: string): string => wrapWithTransaction(fdw.getDeleteFDWSql({ wrapper: { name }, wrapperMeta }));

/** EditWrapperSheet -> fdw-update-mutation, saving the row unchanged. */
const update = (name: string, serverName: string, schema: string, tbl: string): string =>
  wrapWithTransaction(
    fdw.getUpdateFDWSql({
      wrapper: { name },
      wrapperMeta,
      formState: { wrapper_name: name, server_name: serverName, ...creds },
      tables: [table(schema, tbl)],
    }),
  );

const N = 5;
const out = {
  // X01a: five connections created through the dashboard, then Delete on the first row.
  a_create: Array.from({ length: N }, (_, i) => create(`x01a_w${i + 1}`, "x01a_ft", `t_${i + 1}`)),
  a_delete: del("x01a_w1"),
  // X01b / X01c: five servers on one FDW (SQL setup), then Delete or Edit on the first row.
  b_delete: del("x01b_wrapper"),
  c_update: update("x01c_wrapper", "x01c_server_1", "x01c_ft", "t_1"),
  // X01e: the dashboard create form, given the name of an FDW that already exists.
  e_create_existing: create("x01e_wrapper", "x01e_ft", "t_new"),
};

const body = [
  "// GENERATED by scripts/gen-studio-sql.ts - do not edit.",
  `// supabase/supabase ${commit}, packages/pg-meta/src/sql/studio/database/fdw.ts`,
  `export const STUDIO_COMMIT = ${JSON.stringify(commit)};`,
  `export const STUDIO_SQL = ${JSON.stringify(out, null, 2)} as const;`,
  "",
].join("\n");

const outFile = resolve(import.meta.dir, "../lib/studio-sql.generated.ts");
await Bun.write(outFile, body);
console.log(`wrote ${outFile}`);
