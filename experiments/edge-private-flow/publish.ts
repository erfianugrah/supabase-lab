// publish: redacted copies of evidence/run*.json in out/<date>/ plus a facts
// table per run, for RUNLOG and docs to cite (evidence/ is gitignored).
//   bun publish.ts 2026-11-23
// Redacts: the project ref and any other 20-lowercase-letter token, JWTs,
// 32-hex account ids, UUIDs, and the probing client's address (CLIENT_IP env,
// comma-separated). Workers egress and Supabase egress addresses are kept: they
// are the measurement.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const date = process.argv[2];
if (!date) throw new Error("usage: bun publish.ts <YYYY-MM-DD>");
const dir = import.meta.dir;
const outDir = `${dir}/out/${date}`;
mkdirSync(outDir, { recursive: true });
const clientIps = (process.env.CLIENT_IP ?? "").split(",").filter(Boolean);

const redact = (s: string) => {
  let t = s
    .replace(/eyJ[\w-]+\.[\w-]+\.[\w-]+/g, "<jwt>")
    .replace(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/g, "<uuid>")
    .replace(/\b[0-9a-f]{32}\b/g, "<account-id>")
    .replace(/\b[a-z]{20}\b/g, "<ref>");
  for (const ip of clientIps) t = t.split(ip).join("<client-ip>");
  return t;
};

const facts: string[] = [];
for (const f of readdirSync(`${dir}/evidence`).filter((n) => /^run\d?-.*\.json$/.test(n) && n.includes(date)).sort()) {
  const red = redact(readFileSync(`${dir}/evidence/${f}`, "utf8"));
  writeFileSync(`${outDir}/${f}`, red);
  const j = JSON.parse(red);
  facts.push(`## ${f}\n\nat ${j.at}\n\n| row | status | arm | arm ok | arm status | arm ms | detail |\n|---|---|---|---|---|---|---|`);
  for (const r of j.rows) {
    const arms = Array.isArray(r.body?.results) ? r.body.results : [];
    const cell = (x: unknown) => String(x ?? "").replace(/\|/g, "/").replace(/\n/g, " ").slice(0, 140);
    if (arms.length === 0) {
      const extra = r.n ? `n=${r.n} min=${r.min ?? "-"} p50=${r.p50} p90=${r.p90} max=${r.max}` : r.firstB ? `firstB=${JSON.stringify(r.firstB)}` : Array.isArray(r.body) ? `${r.body.length} rows` : cell(JSON.stringify(r.body ?? ""));
      facts.push(`| ${cell(r.id)} | ${r.status ?? "-"} | - | - | - | ${r.ms ?? "-"} | ${cell(extra)} |`);
    }
    for (const a of arms) {
      facts.push(`| ${cell(r.id)} | ${r.status} | ${cell(a.arm)} | ${a.ok} | ${a.status ?? "-"} | ${a.ms} | ${cell(a.error ?? JSON.stringify(a.detail ?? ""))} |`);
    }
  }
  facts.push("");
}
writeFileSync(`${outDir}/facts.md`, `# edge-private-flow facts, ${date}\n\nGenerated by publish.ts from the redacted run files in this directory.\n\n${facts.join("\n")}\n`);
console.log(`published ${outDir}`);
